// Builds tokens.json (W3C design-token format) into:
//   dist/tokens.css          CSS variables, light + dark + Tailwind v4 @theme (web, admin, site)
//   dist/index.js / .d.ts    typed constants (any TypeScript consumer)
//   dist/tailwind-preset.cjs Tailwind v3 preset (NativeWind, mobile)
// No dependencies on purpose: the token file is small and the mapping is explicit.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const root = new URL('.', import.meta.url);
const tokens = JSON.parse(readFileSync(new URL('tokens.json', root), 'utf8'));

const lookup = (path) => path.split('.').reduce((node, key) => node?.[key], tokens);
const resolve = (value) => {
  if (typeof value === 'string' && /^\{.+\}$/.test(value)) {
    const target = lookup(value.slice(1, -1));
    if (target === undefined) throw new Error(`Unresolved token reference ${value}`);
    return resolve(target.$value ?? target);
  }
  return value;
};
const leaves = (group) =>
  Object.entries(group)
    .filter(([key, node]) => !key.startsWith('$') && node && node.$value !== undefined)
    .map(([key, node]) => [key, resolve(node.$value)]);
const px = (value) => Number.parseFloat(value);

const palette = Object.fromEntries(leaves(tokens.color).filter(([, v]) => v !== null));
const themes = {
  light: Object.fromEntries(leaves(tokens.theme.light)),
  dark: Object.fromEntries(leaves(tokens.theme.dark)),
};
themes.oled = { ...themes.dark, ...Object.fromEntries(leaves(tokens.theme.oled)) };
const space = Object.fromEntries(leaves(tokens.space));
const radius = Object.fromEntries(leaves(tokens.radius));
const size = Object.fromEntries(leaves(tokens.size));
const breakpoint = Object.fromEntries(leaves(tokens.breakpoint));
const duration = Object.fromEntries(leaves(tokens.motion.duration));
const easing = Object.fromEntries(leaves(tokens.motion.easing));
const fontFamily = Object.fromEntries(leaves(tokens.font.family));
const fontWeight = Object.fromEntries(leaves(tokens.font.weight));
const typography = Object.fromEntries(leaves(tokens.typography).filter(([key]) => key !== 'scale'));
const shadow = Object.fromEntries(
  leaves(tokens.shadow).map(([key, s]) => [
    key,
    `${s.offsetX} ${s.offsetY} ${s.blur} ${s.spread} ${s.color}`,
  ]),
);
const haptic = Object.fromEntries(leaves(tokens.haptic));
const sound = Object.fromEntries(leaves(tokens.sound));
const tierRingWidth = resolve(tokens.tier['ring-width'].$value);

if (themes.light.bg !== '#FFFFFF' || themes.dark.bg !== '#0A0A0A') {
  throw new Error('Token sanity check failed: Paper / Ink backgrounds changed.');
}
if (process.argv.includes('--check')) process.exit(0);

// ---------- CSS ----------
const vars = (theme) =>
  Object.entries(theme)
    .map(([key, value]) => `  --${key}: ${value};`)
    .join('\n');
const bezier = (v) => `cubic-bezier(${v.join(', ')})`;
const semantic = Object.keys(themes.light);

const css = `/* Generated by @1minitman/tokens from tokens.json v${tokens.$version}. Do not edit. */
:root {
${vars(themes.light)}
  --art-ink: ${palette.ink};
  --art-paper: ${palette.paper};
  --font-sans-stack: ${fontFamily.sans.map((f) => (f.includes(' ') ? `'${f}'` : f)).join(', ')};
  --font-mono-stack: ${fontFamily.mono.map((f) => (f.includes(' ') ? `'${f}'` : f)).join(', ')};
  --tier-ring-width: ${tierRingWidth};
  --touch-min: ${size['touch-min']};
  --elevation-menu: ${shadow.menu};
  --elevation-sheet: ${shadow.sheet};
  --duration-fast: ${duration.fast};
  --duration-base: ${duration.base};
  --duration-slow: ${duration.slow};
  --easing-standard: ${bezier(easing.standard)};
  --easing-exit: ${bezier(easing.exit)};
  color-scheme: light dark;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
${vars(themes.dark).replace(/^/gm, '  ')}
  }
}
:root[data-theme='dark'] {
${vars(themes.dark)}
}

/* Tailwind v4 theme: semantic colours only (no raw hex in components). */
@theme inline {
  --color-*: initial;
${semantic.map((key) => `  --color-${key}: var(--${key});`).join('\n')}
  --color-transparent: transparent;
  --color-current: currentColor;
  --font-sans: var(--font-sans-stack);
  --font-mono: var(--font-mono-stack);
  --radius-*: initial;
${Object.entries(radius)
  .map(([key, value]) => `  --radius-${key}: ${value};`)
  .join('\n')}
  --radius: ${radius.sm};
  --breakpoint-*: initial;
  --breakpoint-sm: ${breakpoint.tablet};
  --breakpoint-md: ${breakpoint.desktop};
  --breakpoint-lg: 1280px;
  --breakpoint-xl: 1440px;
  --container-page: ${breakpoint.max};
  --shadow-*: initial;
  --shadow-menu: var(--elevation-menu);
  --shadow-sheet: var(--elevation-sheet);
  --ease-standard: var(--easing-standard);
}
`;

// ---------- TypeScript / JS ----------
const data = {
  version: tokens.$version,
  palette,
  themes,
  space: Object.fromEntries(Object.entries(space).map(([k, v]) => [k, px(v)])),
  radius: Object.fromEntries(Object.entries(radius).map(([k, v]) => [k, px(v)])),
  size: Object.fromEntries(Object.entries(size).map(([k, v]) => [k, px(v)])),
  breakpoint: Object.fromEntries(Object.entries(breakpoint).map(([k, v]) => [k, px(v)])),
  duration: Object.fromEntries(Object.entries(duration).map(([k, v]) => [k, px(v)])),
  easing,
  fontFamily,
  fontWeight,
  fontSizes: tokens.typography.scale.$value,
  typography,
  shadow,
  tierRingWidth: px(tierRingWidth),
  haptic,
  sound,
};
const js = `// Generated by @1minitman/tokens from tokens.json v${tokens.$version}. Do not edit.
export const tokens = ${JSON.stringify(data, null, 2)};
export const { palette, themes, space, radius, size, breakpoint, duration, easing, fontFamily, fontWeight, fontSizes, typography, shadow, haptic, sound } = tokens;
export default tokens;
`;
const dts = `// Generated by @1minitman/tokens from tokens.json v${tokens.$version}. Do not edit.
export declare const tokens: ${JSON.stringify(data, null, 2)};
export type Tokens = typeof tokens;
export type ThemeName = keyof Tokens['themes'];
export type SemanticColor = keyof Tokens['themes']['light'];
export type HapticKind = keyof Tokens['haptic'];
export type SoundName = keyof Tokens['sound'];
export declare const palette: Tokens['palette'];
export declare const themes: Tokens['themes'];
export declare const space: Tokens['space'];
export declare const radius: Tokens['radius'];
export declare const size: Tokens['size'];
export declare const breakpoint: Tokens['breakpoint'];
export declare const duration: Tokens['duration'];
export declare const easing: Tokens['easing'];
export declare const fontFamily: Tokens['fontFamily'];
export declare const fontWeight: Tokens['fontWeight'];
export declare const fontSizes: Tokens['fontSizes'];
export declare const typography: Tokens['typography'];
export declare const shadow: Tokens['shadow'];
export declare const haptic: Tokens['haptic'];
export declare const sound: Tokens['sound'];
export default tokens;
`;

// ---------- Tailwind v3 preset (NativeWind) ----------
// Semantic colours point at CSS variables; the mobile app sets them per theme with NativeWind vars().
const preset = {
  theme: {
    colors: {
      transparent: 'transparent',
      current: 'currentColor',
      ...Object.fromEntries(semantic.map((key) => [key, `var(--${key})`])),
    },
    borderRadius: { none: '0px', ...radius, DEFAULT: radius.sm },
    spacing: { ...space, px: '1px', touch: size['touch-min'] },
    fontSize: Object.fromEntries(tokens.typography.scale.$value.map((n) => [String(n), `${n}px`])),
    screens: { sm: breakpoint.tablet, md: breakpoint.desktop },
    extend: {},
  },
};
const cjs = `// Generated by @1minitman/tokens from tokens.json v${tokens.$version}. Do not edit.
module.exports = ${JSON.stringify(preset, null, 2)};
`;

mkdirSync(new URL('dist/', root), { recursive: true });
writeFileSync(new URL('dist/tokens.css', root), css);
writeFileSync(new URL('dist/index.js', root), js);
writeFileSync(new URL('dist/index.d.ts', root), dts);
writeFileSync(new URL('dist/tailwind-preset.cjs', root), cjs);
console.log(`tokens v${tokens.$version}: css, ts and tailwind preset written to dist/`);
